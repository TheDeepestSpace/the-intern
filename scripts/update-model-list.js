// Scheduled job (issue #191): keeps a table of currently-valid Claude model
// IDs in the-intern-data's README.md current, so the-intern-data's README
// stays an accurate, non-hallucinated reference for anyone (bot or human)
// looking up which `model=` values the dispatcher trigger syntax accepts.
//
// Source of truth is the live Models API (GET /v1/models), never a
// hand-maintained or model-authored list — that's the whole point of this
// job existing instead of a one-time doc edit.
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execSync } = require('child_process');
const { DATA_REPO, resolveDataRepoRemoteUrl, redactUrl, runWithRetryOnNotFound } = require('./data-repo-remote.js');

const MODELS_API_URL = 'https://api.anthropic.com/v1/models';
const ANTHROPIC_VERSION = '2023-06-01';

// Marker pair the-intern-data's README uses to delimit the generated block.
// The heading lives *inside* the markers (unlike the issue's sketch, which
// put it just above) so a straight indexOf/slice replace is always
// idempotent — no risk of a stray duplicate heading if a human ever edits
// right up to the marker.
const SECTION_START = "<!-- AUTO-GENERATED by the-intern's update-model-list job — do not hand-edit this section -->";
const SECTION_END = '<!-- END AUTO-GENERATED -->';

function runGit(cmd, options = {}) {
  const { allowFailure = false, ...execOptions } = options;
  try {
    return execSync(`git ${cmd}`, { encoding: 'utf8', ...execOptions }).trim();
  } catch (err) {
    if (allowFailure) return '';
    const detail = (err.stderr || err.message || '').toString().trim();
    throw new Error(`git ${redactUrl(cmd)} failed: ${redactUrl(detail)}`);
  }
}

function ensureSafeDirectory(dir) {
  runGit(`config --global --add safe.directory "${dir}"`, { allowFailure: true });
}

// Pulls the-intern-data's default branch name straight from the remote via
// `ls-remote --symref`, rather than a GitHub API call — one less credential
// surface, and it works identically against a local bare repo in tests.
function getDefaultBranch(remoteUrl, options = {}) {
  const output = runGit(`ls-remote --symref ${remoteUrl} HEAD`, options);
  const match = output.match(/^ref:\s+refs\/heads\/(\S+)\s+HEAD/m);
  if (!match) {
    throw new Error(`could not determine default branch from ls-remote output: ${redactUrl(output)}`);
  }
  return match[1];
}

async function fetchModels(apiKey, fetchImpl = fetch) {
  const models = [];
  let afterId = null;
  do {
    const url = new URL(MODELS_API_URL);
    url.searchParams.set('limit', '1000');
    if (afterId) url.searchParams.set('after_id', afterId);

    const res = await fetchImpl(url.toString(), {
      headers: {
        'x-api-key': apiKey,
        'anthropic-version': ANTHROPIC_VERSION,
      },
    });
    if (!res.ok) {
      throw new Error(`Models API request failed (${res.status}): ${await res.text()}`);
    }
    const data = await res.json();
    models.push(...(data.data || []));
    afterId = data.has_more ? data.last_id : null;
  } while (afterId);
  return models;
}

function formatTokenCount(n) {
  if (typeof n !== 'number' || !Number.isFinite(n)) return '—';
  if (n !== 0 && n % 1_000_000 === 0) return `${n / 1_000_000}M`;
  if (n !== 0 && n % 1_000 === 0) return `${n / 1_000}K`;
  return String(n);
}

// Deliberately just ID / display name / context / max output — no pricing
// column. The Models API doesn't return pricing, and a hand-maintained
// pricing column would drift exactly like the list this job replaces.
function buildTable(models) {
  const header = '| Model | ID (use with `model=`) | Context | Max Output |\n|---|---|---|---|';
  const rows = models.map((m) => {
    const context = formatTokenCount(m.max_input_tokens);
    const maxOutput = formatTokenCount(m.max_tokens);
    return `| ${m.display_name || m.id} | \`${m.id}\` | ${context} | ${maxOutput} |`;
  });
  return [header, ...rows].join('\n');
}

function buildSection(models, timestamp) {
  return [
    SECTION_START,
    `<!-- Last updated: ${timestamp} -->`,
    '',
    '## Current Claude Models',
    '',
    buildTable(models),
    '',
    SECTION_END,
  ].join('\n');
}

function stripTimestampLine(section) {
  return section.replace(/<!-- Last updated: .*? -->\n?/, '');
}

// Replaces the marker-delimited block in `readme` with `section` (appending
// a new block at the end if none exists yet). `changed` ignores the
// timestamp comment so a re-run with no upstream model changes is a true
// no-op — no commit, no push, no PR — rather than a daily timestamp-only churn.
function upsertReadme(readme, section) {
  const startIdx = readme.indexOf(SECTION_START);
  const endIdx = readme.indexOf(SECTION_END);

  if (startIdx !== -1 && endIdx !== -1 && endIdx > startIdx) {
    const existingBlock = readme.slice(startIdx, endIdx + SECTION_END.length);
    const changed = stripTimestampLine(existingBlock) !== stripTimestampLine(section);
    const content = `${readme.slice(0, startIdx)}${section}${readme.slice(endIdx + SECTION_END.length)}`;
    return { content, changed };
  }

  const trimmed = readme.replace(/\s+$/, '');
  const content = trimmed ? `${trimmed}\n\n${section}\n` : `${section}\n`;
  return { content, changed: true };
}

function authHeaders(token) {
  return {
    Authorization: `Bearer ${token}`,
    Accept: 'application/vnd.github+json',
    'User-Agent': 'the-intern-bot-update-model-list',
  };
}

async function createPullRequest(token, { title, head, base, body }, fetchImpl = fetch) {
  const res = await fetchImpl(`https://api.github.com/repos/${DATA_REPO}/pulls`, {
    method: 'POST',
    headers: { ...authHeaders(token), 'Content-Type': 'application/json' },
    body: JSON.stringify({ title, head, base, body }),
  });
  if (!res.ok) {
    throw new Error(`create PR failed (${res.status}): ${await res.text()}`);
  }
  return res.json();
}

async function mergePullRequest(token, pullNumber, fetchImpl = fetch) {
  const res = await fetchImpl(`https://api.github.com/repos/${DATA_REPO}/pulls/${pullNumber}/merge`, {
    method: 'PUT',
    headers: { ...authHeaders(token), 'Content-Type': 'application/json' },
    body: JSON.stringify({ merge_method: 'squash' }),
  });
  if (!res.ok) {
    throw new Error(`merge PR failed (${res.status}): ${await res.text()}`);
  }
  return res.json();
}

async function main(env = process.env, deps = {}) {
  const {
    fetchModelsFn = fetchModels,
    createPullRequestFn = createPullRequest,
    mergePullRequestFn = mergePullRequest,
  } = deps;

  if (!env.ANTHROPIC_API_KEY) {
    console.error('::error::ANTHROPIC_API_KEY is required to query the Models API.');
    process.exitCode = 1;
    return;
  }

  let remoteUrl;
  try {
    remoteUrl = await resolveDataRepoRemoteUrl();
  } catch (err) {
    console.error(`::error::${err.message}`);
    process.exitCode = 1;
    return;
  }
  if (!remoteUrl) {
    console.error('::error::the-intern-data remote is not configured (DATA_REPO_TOKEN or DATA_REPO_REMOTE_URL); cannot update README.');
    process.exitCode = 1;
    return;
  }

  // Fetch models first, before touching git at all — a failure here must
  // never overwrite the README's existing (good) section with anything.
  let models;
  try {
    models = await fetchModelsFn(env.ANTHROPIC_API_KEY);
    if (!models.length) throw new Error('Models API returned an empty list');
  } catch (err) {
    console.error(`::error::Failed to fetch models from the Models API: ${err.message}`);
    process.exitCode = 1;
    return;
  }
  models.sort((a, b) => String(a.id).localeCompare(String(b.id)));

  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'update-model-list-'));
  try {
    ensureSafeDirectory(tmpDir);
    runGit('init -q', { cwd: tmpDir });
    runGit('config user.name "the-intern-bot[bot]"', { cwd: tmpDir });
    runGit('config user.email "the-intern-bot[bot]@users.noreply.github.com"', { cwd: tmpDir });

    let defaultBranch;
    try {
      defaultBranch = getDefaultBranch(remoteUrl, { cwd: tmpDir });
    } catch (err) {
      console.error(`::error::Could not determine the-intern-data's default branch: ${err.message}`);
      process.exitCode = 1;
      return;
    }

    await runWithRetryOnNotFound(remoteUrl, (url) => runGit(`fetch ${url} ${defaultBranch}:${defaultBranch}`, { cwd: tmpDir }));
    runGit(`checkout ${defaultBranch}`, { cwd: tmpDir });

    const readmePath = path.join(tmpDir, 'README.md');
    const readme = fs.existsSync(readmePath) ? fs.readFileSync(readmePath, 'utf8') : '';

    const timestamp = new Date().toISOString();
    const section = buildSection(models, timestamp);
    const { content, changed } = upsertReadme(readme, section);

    if (!changed) {
      console.log('README.md model table is already up to date; nothing to commit.');
      return;
    }

    fs.writeFileSync(readmePath, content, 'utf8');
    runGit('add README.md', { cwd: tmpDir });
    runGit(`commit -q -m "Update Claude model list (${timestamp})"`, { cwd: tmpDir });

    const shortBranch = `update-model-list-${timestamp.slice(0, 10)}`;

    // Always push the short-lived branch first: it's our durable record of
    // this update no matter which path below succeeds or fails next.
    await runWithRetryOnNotFound(remoteUrl, (url) => runGit(`push ${url} ${defaultBranch}:refs/heads/${shortBranch}`, { cwd: tmpDir }));

    let pushedDirectly = false;
    try {
      runGit(`push ${remoteUrl} ${defaultBranch}:refs/heads/${defaultBranch}`, { cwd: tmpDir });
      pushedDirectly = true;
    } catch (err) {
      console.log(`Direct push to ${defaultBranch} was rejected (likely branch protection): ${err.message}`);
    }

    if (pushedDirectly) {
      console.log(`Pushed model list update directly to the-intern-data's ${defaultBranch} branch.`);
      try {
        runGit(`push ${remoteUrl} :refs/heads/${shortBranch}`, { cwd: tmpDir });
      } catch (err) {
        console.warn(`::warning::Could not delete now-redundant branch ${shortBranch}: ${err.message}`);
      }
      return;
    }

    if (!env.DATA_REPO_TOKEN) {
      console.error(`::error::Direct push to ${defaultBranch} failed and DATA_REPO_TOKEN is unavailable to open a fallback PR. Branch ${shortBranch} was pushed to the-intern-data; open a PR from it manually.`);
      process.exitCode = 1;
      return;
    }

    let pr;
    try {
      pr = await createPullRequestFn(env.DATA_REPO_TOKEN, {
        title: `Update Claude model list (${timestamp.slice(0, 10)})`,
        head: shortBranch,
        base: defaultBranch,
        body: [
          "Auto-generated by the-intern's `update-model-list` scheduled job.",
          '',
          `${defaultBranch} appears to be protected against direct pushes, so this PR carries the update instead. The table is regenerated from the live Models API (\`GET /v1/models\`), not hand-authored — safe to merge.`,
        ].join('\n'),
      });
    } catch (err) {
      console.error(`::error::Direct push to ${defaultBranch} failed and PR creation also failed: ${err.message}`);
      process.exitCode = 1;
      return;
    }

    console.log(`Opened PR #${pr.number} on ${DATA_REPO} (${defaultBranch} appears protected).`);

    try {
      await mergePullRequestFn(env.DATA_REPO_TOKEN, pr.number);
      console.log(`Auto-merged PR #${pr.number}.`);
    } catch (err) {
      console.log(`Could not auto-merge PR #${pr.number} (likely requires a review the token can't satisfy): ${err.message}. Leaving it open for manual merge.`);
    }
  } finally {
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
}

if (require.main === module) {
  main().catch((err) => {
    console.error('Fatal error in update-model-list:', err.message);
    process.exitCode = 1;
  });
}

module.exports = {
  formatTokenCount,
  buildTable,
  buildSection,
  upsertReadme,
  fetchModels,
  getDefaultBranch,
  createPullRequest,
  mergePullRequest,
  main,
};
